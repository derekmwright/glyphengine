const (
	glyphW     = 5 // pixels wide per character
	glyphH     = 7 // pixels tall per character
	charGap    = 1 // pixels between characters
	lineGap    = 2 // extra pixels between lines
	maxChars   = 256
	maxPixels  = maxChars * 20 // avg ~20 lit pixels per char
	maxVerts   = maxPixels * 4
	maxIndices = maxPixels * 6
)

// TextLine describes one line of text to render.
type TextLine struct {
	Text  string
	X, Y  float32 // screen position. Negative X = right-aligned with |X| as right margin.
	Scale float32
	Color [3]float32
	Alpha float32 // 0 means fully opaque (default), otherwise 0..1.
	Font  *Font   // nil = default font
}

// TextOverlay renders bitmap text as colored quads.
type TextOverlay struct {
	mesh *Mesh
}

// NewTextOverlay allocates a reusable dynamic mesh for text rendering.
func NewTextOverlay(r *Renderer) (*TextOverlay, error) {
	m, err := r.CreateDynamicIndexedMesh(maxVerts, maxIndices)
	if err != nil {
		return nil, err
	}
	return &TextOverlay{mesh: m}, nil
}

// SetText rebuilds the mesh with quads for each lit pixel in the text lines.
func (t *TextOverlay) SetText(r *Renderer, lines []TextLine, screenW, screenH float32) {
	var vertices []Vertex
	var indices []uint16

	for _, line := range lines {
		s := line.Scale
		cellW := float32(glyphW+charGap) * s
		textW := float32(len(line.Text)) * cellW

		x0 := line.X
		if x0 < 0 {
			// Right-aligned: |X| is right margin
			x0 = screenW - textW + float32(charGap)*s + x0
		}
		y0 := line.Y

		for ci, ch := range line.Text {
			if ch < 0 || ch >= 128 {
				ch = '?'
			}
			glyph := glyphData[ch]
			charX := x0 + float32(ci)*cellW

			for row := 0; row < glyphH; row++ {
				bits := glyph[row]
				for col := 0; col < glyphW; col++ {
					if bits&(1<<uint(glyphW-1-col)) == 0 {
						continue
					}
					px := charX + float32(col)*s
					py := y0 + float32(row)*s

					base := uint16(len(vertices))
					vertices = append(vertices,
						Vertex{Pos: [3]float32{px, py, 0}, Color: line.Color, Normal: [3]float32{0, 0, 0}},
						Vertex{Pos: [3]float32{px + s, py, 0}, Color: line.Color, Normal: [3]float32{0, 0, 0}},
						Vertex{Pos: [3]float32{px + s, py + s, 0}, Color: line.Color, Normal: [3]float32{0, 0, 0}},
						Vertex{Pos: [3]float32{px, py + s, 0}, Color: line.Color, Normal: [3]float32{0, 0, 0}},
					)
					indices = append(indices,
						base, base+1, base+2,
						base+2, base+3, base,
					)
				}
			}
		}
	}

	// Clamp to buffer limits
	if len(vertices) > maxVerts {
		vertices = vertices[:maxVerts]
		indices = indices[:maxIndices]
	}

	r.UpdateMeshData(t.mesh, vertices, indices)
}

// RenderObject returns a RenderObject for drawing this overlay with an orthographic MVP.
func (t *TextOverlay) RenderObject(screenW, screenH float32) RenderObject {
	// Ortho(0,W, 0,H, -1,1) maps screen coords (Y-down) directly to Vulkan clip space
	// where clipY=-1 is top and clipY=+1 is bottom. No Y-flip needed — unlike perspective,
	// the ortho matrix has a non-zero Y translation that would break if we only negated proj[5].
	proj := mgl32.Ortho(0, screenW, 0, screenH, -1, 1)
	return RenderObject{
		Mesh:  t.mesh,
		MVP:   proj,
		Color: [3]float32{1, 1, 1},
	}
}

// Destroy frees the overlay's GPU resources.
func (t *TextOverlay) Destroy(r *Renderer) {
	r.DestroyMesh(t.mesh)
}
